CREATE TABLE IF NOT EXISTS fleetsync.speed_quality_daily (
 unit varchar(60) NOT NULL,work_date date NOT NULL,source_version integer NOT NULL,
 source_count integer NOT NULL,source_sum numeric(20,4) NOT NULL,source_max numeric(12,4) NOT NULL,
 total_count integer NOT NULL,moving_count integer NOT NULL,speed_sum numeric(20,4) NOT NULL,max_speed numeric(12,4) NOT NULL,
 anomaly_count integer NOT NULL,verified_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(unit,work_date),FOREIGN KEY(unit,work_date) REFERENCES fleetsync.speed_daily(unit,work_date) ON DELETE CASCADE
);
ALTER TABLE fleetsync.speed_quality_daily ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON fleetsync.speed_quality_daily FROM PUBLIC;
CREATE OR REPLACE VIEW fleetsync.speed_reporting AS
 SELECT d.unit,d.work_date,d.version,d.source,
 CASE WHEN d.max_speed<80 THEN d.total_count ELSE coalesce(q.total_count,0) END AS total_count,
 CASE WHEN d.max_speed<80 THEN d.moving_count ELSE coalesce(q.moving_count,0) END AS moving_count,
 CASE WHEN d.max_speed<80 THEN d.speed_sum ELSE coalesce(q.speed_sum,0) END AS speed_sum,
 CASE WHEN d.max_speed<80 THEN d.max_speed ELSE q.max_speed END AS max_speed,
 d.total_count AS source_count,
 CASE WHEN d.max_speed>=80 THEN coalesce(q.anomaly_count,0) ELSE 0 END AS anomaly_count,
 CASE WHEN d.max_speed>=80 AND q.unit IS NULL THEN d.total_count ELSE 0 END AS pending_count
 FROM fleetsync.speed_daily d LEFT JOIN fleetsync.speed_quality_daily q ON q.unit=d.unit AND q.work_date=d.work_date
 AND q.source_version=d.version AND q.source_count=d.total_count AND q.source_sum=d.speed_sum AND q.source_max=d.max_speed;
REVOKE ALL ON fleetsync.speed_reporting FROM PUBLIC;

CREATE TABLE IF NOT EXISTS fleetsync.occ_meetings (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title varchar(180) NOT NULL,start_at timestamptz NOT NULL,end_at timestamptz NOT NULL,
 meeting_url text NOT NULL DEFAULT '',notes text NOT NULL DEFAULT '',version integer NOT NULL DEFAULT 1,
 created_by bigint REFERENCES fleetsync.users(id) ON DELETE SET NULL,updated_at timestamptz NOT NULL DEFAULT now(),
 CHECK(end_at>start_at)
);
CREATE INDEX IF NOT EXISTS occ_meetings_start ON fleetsync.occ_meetings(start_at);
ALTER TABLE fleetsync.occ_meetings ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON fleetsync.occ_meetings FROM PUBLIC;
