CREATE SCHEMA IF NOT EXISTS fleetsync;
REVOKE ALL ON SCHEMA fleetsync FROM PUBLIC;
CREATE TABLE IF NOT EXISTS fleetsync.app_settings (
  setting_key varchar(80) PRIMARY KEY,
  setting_value text NOT NULL
);
INSERT INTO fleetsync.app_settings VALUES ('bootstrap', '0') ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS fleetsync.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(120) NOT NULL,
  username varchar(80) NOT NULL,
  password_hash varchar(255) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS users_username ON fleetsync.users (lower(username));
ALTER TABLE fleetsync.users ADD COLUMN IF NOT EXISTS is_admin boolean NOT NULL DEFAULT false;
ALTER TABLE fleetsync.users ADD COLUMN IF NOT EXISTS must_change_password boolean NOT NULL DEFAULT false;
ALTER TABLE fleetsync.users ADD COLUMN IF NOT EXISTS can_edit_data boolean NOT NULL DEFAULT false;
UPDATE fleetsync.users SET is_admin=true
WHERE id=(SELECT min(id) FROM fleetsync.users)
  AND NOT EXISTS (SELECT 1 FROM fleetsync.users WHERE is_admin);
CREATE TABLE IF NOT EXISTS fleetsync.email_recovery (
  user_id bigint PRIMARY KEY REFERENCES fleetsync.users(id) ON DELETE CASCADE,
  email varchar(254),
  pending_email varchar(254),
  verify_hash char(64),
  verify_expires_at timestamptz,
  reset_hash char(64),
  reset_expires_at timestamptz,
  last_sent_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS fleetsync.operators (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site varchar(10) NOT NULL CHECK (site IN ('BCP','ACP','KCP','SSCP')),
  nik varchar(60) NOT NULL,
  name varchar(150) NOT NULL,
  unit varchar(60) NOT NULL DEFAULT '',
  equipment varchar(100) NOT NULL DEFAULT '',
  last_date date,
  version integer NOT NULL DEFAULT 1,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (site, nik)
);
CREATE INDEX IF NOT EXISTS operators_name ON fleetsync.operators (site, name);
CREATE TABLE IF NOT EXISTS fleetsync.lineups (
  id varchar(80) PRIMARY KEY,
  site varchar(10) NOT NULL CHECK (site IN ('BCP','ACP','KCP','SSCP')),
  work_date date NOT NULL,
  shift varchar(30) NOT NULL DEFAULT 'Belum ditentukan' CHECK (shift IN ('D','N','Belum ditentukan')),
  type_category varchar(30) NOT NULL DEFAULT 'Belum diklasifikasi' CHECK (type_category IN ('Production','Support','Belum diklasifikasi')),
  unit varchar(60) NOT NULL,
  equipment varchar(100) NOT NULL DEFAULT '',
  operator_name varchar(150) NOT NULL DEFAULT '',
  nik varchar(60) NOT NULL DEFAULT '',
  dh varchar(20) NOT NULL DEFAULT 'Ya' CHECK (dh IN ('Ya','Tidak','Belum dicek')),
  mine varchar(20) NOT NULL DEFAULT 'Belum dicek' CHECK (mine IN ('Ya','Tidak','Belum dicek')),
  ftw varchar(20) NOT NULL DEFAULT 'Belum dicek' CHECK (ftw IN ('Ya','Tidak','Belum dicek')),
  source_status varchar(150) NOT NULL DEFAULT '',
  note text NOT NULL DEFAULT '',
  proof_ftw varchar(255) NOT NULL DEFAULT '',
  proof_mine varchar(255) NOT NULL DEFAULT '',
  source varchar(150) NOT NULL DEFAULT 'Input FleetSync',
  source_row integer,
  version integer NOT NULL DEFAULT 1,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (site, work_date, shift, unit, nik)
);
CREATE INDEX IF NOT EXISTS lineups_filter ON fleetsync.lineups (site, work_date, shift, type_category);
CREATE INDEX IF NOT EXISTS lineups_operator ON fleetsync.lineups (site, nik);
CREATE TABLE IF NOT EXISTS fleetsync.audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint REFERENCES fleetsync.users(id) ON DELETE SET NULL,
  action varchar(50) NOT NULL,
  entity_type varchar(40) NOT NULL,
  entity_id varchar(80) NOT NULL DEFAULT '',
  details jsonb NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS audit_time ON fleetsync.audit_logs (created_at DESC);
CREATE TABLE IF NOT EXISTS fleetsync.login_attempts (
  attempt_key varchar(100) PRIMARY KEY,
  attempts integer NOT NULL DEFAULT 0,
  last_attempt timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS fleetsync.sessions (
  id char(64) PRIMARY KEY,
  user_id bigint REFERENCES fleetsync.users(id) ON DELETE CASCADE,
  csrf char(64) NOT NULL,
  flash jsonb,
  expires_at timestamptz NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_expiry ON fleetsync.sessions (expires_at);
CREATE TABLE IF NOT EXISTS fleetsync.upload_tickets (
  id char(64) PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES fleetsync.users(id) ON DELETE CASCADE,
  path varchar(255) NOT NULL UNIQUE,
  kind varchar(30) NOT NULL CHECK (kind IN ('proof_ftw','proof_mine','spreadsheet')),
  extension varchar(8) NOT NULL,
  expires_at timestamptz NOT NULL,
  consumed_at timestamptz
);
CREATE INDEX IF NOT EXISTS tickets_expiry ON fleetsync.upload_tickets (expires_at);
-- Application tables are private server-side tables, never exposed through PostgREST.
REVOKE ALL ON ALL TABLES IN SCHEMA fleetsync FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA fleetsync FROM PUBLIC;
